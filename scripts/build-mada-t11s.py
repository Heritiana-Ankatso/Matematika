"""Build the native Malagasy T11 S course PDFs (student and teacher, French only) from content/tex/courses/mada-t11s.

Unpublished (owner decision, 16 November 2026, same rule as T10): the course is not in content/data/manifest.json, so there are no generated
mains for it. This builder writes its own two mains (one chapter per unit, class mxbook, French only: Malagasy curriculum
lessons are in French, there is no English twin), compiles them with the shared driver (mxbuild.tex) and leaves the two
PDFs in build/out/tex/mada-t11s/ (ignored by git). Nothing is written to dist/ and the manifest is not read or changed.

Entry point: `make tex COURSE=mada-t11s` (or `python3 scripts/build-mada-t11s.py`). Publication (later, after the two
independent audits and the owner's approval) adds the manifest course and chapter and cuts these PDFs into excerpts.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'build'))
from mxbuild import tex   # noqa: E402

COURSE = 'mada-t11s'
SRC = ROOT / 'content/tex/courses' / COURSE
BUILD = ROOT / 'build/out/tex' / COURSE
UNITS = ['c01']   # one entry per chapter; each later chapter of the course is appended here
CORE = str(ROOT / 'content/tex/core')


def main_text(edition):
    lines = ['% GENERATED by scripts/build-mada-t11s.py; do not edit.',
             r'\makeatletter\def\input@path{{%s/}}\makeatother\def\mxcorepath{%s/}' % (CORE, CORE),
             r'\documentclass[course=%s,lang=fr,edition=%s,layout=booklet]{mxbook}' % (COURSE, edition),
             r'\begin{document}']
    lines += [r'\mxinclude{%s}' % u for u in UNITS]
    lines.append(r'\end{document}')
    return '\n'.join(lines) + '\n'


def main():
    mains = BUILD / 'mains'; mains.mkdir(parents=True, exist_ok=True)
    for edition, name in (('student', 'eleve'), ('teacher', 'professeur')):
        (mains / f'{name}.tex').write_text(main_text(edition))
        res = tex.compile(SRC, str(mains / f'{name}.tex'), f'{COURSE}-{name}', BUILD, max_runs=4)
        res.report(f'{COURSE}-{name}')
        print(f'  {res.pdf}')


if __name__ == '__main__':
    main()
