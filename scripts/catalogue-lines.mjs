// Writes two generated modules, read from the modules themselves (docs/REBUILD_PLAN.md stage 1):
// - site/js/catalogue-lines.js: the catalogue lines of the experiments, the gallery and the challenges (ids, titles,
//   missions, links). Pages that only name these entries (chapter pages, Olympiad, reading) read the lines and load an
//   experiment or a challenge only to show it.
// - site/js/discovery-context-data.js: for every address of the site index (discovery.js, live in this edition), its first
//   field and the four resources that follow the idea: the box "Cette idée dans le site" at the end of a page, without
//   loading every collection to build the index.
// Run by build/mxbuild/content_index.py (`make site`, needs dist/js/resources-data.js); `--print` prints both as JSON.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const { EXPERIMENTS } = await import('../site/js/lab/registry.js');
const { labs } = await import('../site/js/content.js');
const { challengeBase, challenges } = await import('../site/js/content.js').then(async (m) => ({ ...(await import('../site/js/challenges/registry.js')), challenges: m.challenges }));
const { discoveryIndex } = await import('../site/js/discovery.js');
const { recommendations, FORMAT_LABELS } = await import('../site/js/discovery-index.js');
const { membershipByKey } = await import('../site/js/topic-registry.js');
const { liveDiscovery, liveCompanionCatalog } = await import('../site/js/live-curriculum.js');
const { resourceCatalog } = await import('../dist/js/resources-data.js');

const pick = (x, keys) => Object.fromEntries(keys.filter((k) => x[k] !== undefined).map((k) => [k, x[k]]));
const lines = {
  // what a lab reference resolves to without the experiment's code (lab/refs.js)
  EXPERIMENT_LINES: EXPERIMENTS.map((e) => ({ ...pick(e, ['id', 'title', 'short']), missions: e.missions.map((m) => m.id) })),
  // content.js `labs`: the experiments' catalogue entries and the gallery curiosities
  LAB_LINES: labs.map((l) => pick(l, ['id', 'custom', 'title', 'short', 'group', 'links'])),
  // content.js `challenges` without statements and solutions
  CHALLENGE_LINES: challengeBase.map((c) => pick(c, ['id', 'type', 'title', 'topic', 'difficulty', 'minutes'])),
};
// The same index as the site builds (app.js before stage 1): live entries, live related routes.
const index = liveDiscovery(discoveryIndex({ labs, challenges, chapters: liveCompanionCatalog(resourceCatalog).chapters }));
const context = Object.fromEntries(index.map((item) => {
  const k = item.memberships[0] && membershipByKey(item.memberships[0]);
  return [item.route, {
    field: k ? { key: item.memberships[0], topic: k.topic.title, subtopic: k.subtopic.title } : null,
    next: recommendations(index, item.route).map((x) => ({ route: x.route, title: x.title, format: FORMAT_LABELS[x.format] })),
  }];
}));
const module = (from, values) => `// Generated by scripts/catalogue-lines.mjs from ${from}; do not edit.\n`
  + Object.entries(values).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};`).join('\n') + '\n';
const files = {
  'site/js/catalogue-lines.js': module('lab/registry.js, content.js and challenges/registry.js', lines),
  'site/js/discovery-context-data.js': module('the site index of discovery.js', { DISCOVERY_CONTEXT: context }),
};
if (process.argv.includes('--print')) process.stdout.write(JSON.stringify(files));
else for (const [path, text] of Object.entries(files)) writeFileSync(fileURLToPath(new URL('../' + path, import.meta.url)), text);
